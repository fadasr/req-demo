#!/usr/bin/env python3
"""Render the full V-model matrix the demo's claims support.

req keeps three views that the upstream puts on one traceability page:

  requirements <-> requirements   `req trace --format json` (claims and their relations)
  requirements <-> design/code    `req satisfy --format json` (design elements and their links)
  requirements <-> tests          each trace node's `tests` (authored JUnit ids)

This script joins them into one Markdown document for a reader. It is a demo tool, not a req
projection: `req check` cannot verify it, and it must be regenerated after a corpus change.

    scripts/build-trace-matrix.py                 # print
    scripts/build-trace-matrix.py --out docs/traceability.md
"""
import argparse
import json
import pathlib
import re
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent


def req(args, document=False):
    completed = subprocess.run(
        ["req", *args], cwd=ROOT, capture_output=True, text=True, check=False
    )
    if completed.returncode != 0:
        detail = completed.stderr.strip() or completed.stdout.strip() or "no output"
        raise SystemExit(f"req {' '.join(args)} exited {completed.returncode}: {detail}")
    return json.loads(completed.stdout) if document else completed.stdout


def short(text, limit=90):
    text = " ".join((text or "").split())
    return text if len(text) <= limit else text[: limit - 3].rstrip() + "..."


def built_from(text):
    match = re.search(r"^\s*built from\s+(\S+)", text, re.MULTILINE)
    return match.group(1) if match else "unknown"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out", metavar="<file>", help="write the document here instead of stdout")
    args = parser.parse_args()

    trace = req(["trace", "--format", "json"], document=True)
    satisfy = req(["satisfy", "--format", "json"], document=True)
    version = built_from(req(["--version"]))

    design = {}
    for link in satisfy["links"]:
        design.setdefault(link["claim_id"], []).append(link)
    elements = sorted({link["element"] for link in satisfy["links"]})
    nodes = sorted(trace["nodes"], key=lambda node: (node["area"] or "", node["claim_id"]))

    with_design = sum(1 for node in nodes if design.get(node["claim_id"]))
    with_tests = sum(1 for node in nodes if node["tests"])
    test_links = sum(len(node["tests"]) for node in nodes)
    lines = [
        "<!-- generated by scripts/build-trace-matrix.py from `req trace --format json` and",
        f"     `req satisfy --format json`; rules_v {trace['rules_v']}; req built from {version}.",
        "     Regenerate after a corpus change; do not edit by hand. -->",
        "",
        "# Traceability",
        "",
        f"{len(nodes)} claims · {with_design} with a design/code element · {with_tests} with a "
        f"linked test ({test_links} test link(s)) · {len(elements)} design element(s) · "
        f"{len(trace['edges'])} requirement relation(s).",
        "",
        "A claim's design elements are the files under `design/` that declare "
        "`req-satisfies: <claim-id>`; a test is a JUnit `classname::name` in the claim's `tests:`.",
        "",
        "## Requirements by area",
        "",
    ]

    areas = {}
    for node in nodes:
        areas.setdefault(node["area"] or "(no area)", []).append(node)

    for area, rows in areas.items():
        lines += [f"### {area}", "", "| claim | requirement | design / code | tests | derives from |",
                  "| --- | --- | --- | --- | --- |"]
        for node in rows:
            claim = node["claim_id"]
            elements_cell = "<br>".join(
                f"`{link['element']}`" for link in design.get(claim, [])
            ) or "—"
            tests_cell = "<br>".join(f"`{test.split('::')[-1]}`" for test in node["tests"]) or "—"
            outgoing = [
                edge for edge in trace["edges"] if edge["from"] == claim
            ]
            relations = "<br>".join(
                f"{edge['relation']} → {edge['to']}" for edge in outgoing
            ) or "—"
            lines.append(
                f"| {claim} | {short(node['statement'])} | {elements_cell} | {tests_cell} | {relations} |"
            )
        lines.append("")

    lines += ["## Design elements", "", "| element | claims it satisfies | status |",
              "| --- | --- | --- |"]
    for element in elements:
        links = [link for link in satisfy["links"] if link["element"] == element]
        claims = "<br>".join(
            f"{link['claim_id']} ({link['outcome']})" for link in sorted(links, key=lambda l: l["claim_id"])
        )
        lines.append(f"| `{element}` | {claims} | {short(', '.join(sorted({l['outcome'] for l in links})))} |")
    lines.append("")

    gaps = [node for node in nodes if not design.get(node["claim_id"])]
    untested = [node for node in nodes if not node["tests"]]
    lines += [
        "## Coverage",
        "",
        f"- claims with no design/code element: **{len(gaps)}** "
        f"({', '.join(node['claim_id'] for node in gaps)})",
        f"- claims with no linked test: **{len(untested)}** "
        f"({', '.join(node['claim_id'] for node in untested[:20])}"
        + (", …" if len(untested) > 20 else "") + ")",
        "",
    ]

    text = "\n".join(lines) + "\n"
    if args.out:
        path = pathlib.Path(args.out)
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
        print(f"wrote {path}")
    else:
        sys.stdout.write(text)


if __name__ == "__main__":
    main()
